#!/usr/bin/env python3
"""Converts art/ into src/render/Art.{h,cpp}.

Every picture the 3D view draws (walls, enemies, effects, the hand, items lying on the floor)
becomes a Bitmap: up to 63 colours, texels stored a column at a time (the raycaster walks a
column per screen column) with index 0 transparent, and the palette precomputed at SHADES
distance levels plus one hit-flash row, byte-swapped RGB565 so a texel goes to the panel without
any arithmetic. Light falls off warm: blue fades first, like torchlight.

Items also become 16x16 RGB565 icons for the menus, black transparent like the idle game's.

Run from the game's folder after tools/make_placeholders.py: python3 tools/convert_art.py
"""
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "art"
OUT_H = ROOT / "src" / "render" / "Art.h"
OUT_CPP = ROOT / "src" / "render" / "Art.cpp"

SHADES = 16
MAX_COLORS = 63
ALPHA_CUTOFF = 128
NEAR_BLACK = 0x0020

# Order is the enum order; Config.h and the renderer count on it
WALLS = ["crypt", "stone", "sewer", "bone", "blood", "portal_0", "portal_1", "sealed"]
ENEMIES = ["small_rat", "slime", "zombie", "goblin", "spider", "frog_wizard", "big_bad_rat", "skeleton",
           "wraith", "lich"]
FX = ["fireball", "bolt", "spark"]
HAND = ["sword_idle", "sword_swing", "hand_charge", "hand_cast"]
SLOTS = ["weapon", "focus", "armor", "helm", "boots", "ring", "amulet"]
TIERS = "abcde"


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def swap(c):
    return ((c >> 8) | (c << 8)) & 0xFFFF


def shaded(rgb, level):
    f = 0.82 ** level
    r, g, b = rgb
    return rgb565(int(r * f), int(g * f ** 1.1), int(b * f ** 1.3))


def flashed(rgb):
    return rgb565(*(int(v * 0.45 + w * 0.55) for v, w in zip(rgb, (255, 240, 220))))


def bitmap(name, path):
    im = Image.open(path).convert("RGBA")
    w, h = im.size
    if w > 255 or h > 255:
        sys.exit(f"{path}: too big")
    opaque = [(x, y) for y in range(h) for x in range(w) if im.getpixel((x, y))[3] >= ALPHA_CUTOFF]
    rgb = im.convert("RGB")
    colors = sorted({rgb.getpixel(p) for p in opaque})
    if len(colors) > MAX_COLORS:
        q = rgb.quantize(colors=MAX_COLORS, method=Image.Quantize.MEDIANCUT)
        pal = q.getpalette()[: MAX_COLORS * 3]
        lookup = {p: q.getpixel(p) for p in opaque}
        colors = [tuple(pal[i * 3: i * 3 + 3]) for i in range(MAX_COLORS)]
        index = {p: lookup[p] + 1 for p in opaque}
    else:
        pos = {c: i + 1 for i, c in enumerate(colors)}
        index = {p: pos[rgb.getpixel(p)] for p in opaque}
    stride = len(colors) + 1
    texels = [index.get((x, y), 0) for x in range(w) for y in range(h)]
    shades = []
    for level in range(SHADES):
        shades += [0] + [swap(shaded(c, level)) for c in colors]
    shades += [0] + [swap(flashed(c)) for c in colors]
    return name, w, h, stride, texels, shades


def icon565(path):
    im = Image.open(path).convert("RGBA")
    if im.size != (16, 16):
        sys.exit(f"{path}: expected 16x16")
    out = []
    for y in range(16):
        for x in range(16):
            r, g, b, a = im.getpixel((x, y))
            c = rgb565(r, g, b) if a >= ALPHA_CUTOFF else 0
            if a >= ALPHA_CUTOFF and c == 0:
                c = NEAR_BLACK
            out.append(swap(c))
    return out


def words(values, per_line=16, fmt="0x{:04X}"):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(fmt.format(v) for v in values[i: i + per_line]) + ",")
    return "\n".join(lines)


def main():
    groups = [
        ("WALL", [(n, ART / "walls" / f"{n}.png") for n in WALLS]),
        ("ENEMY", [(n, ART / "enemies" / f"{n}.png") for n in ENEMIES]),
        ("FX", [(n, ART / "fx" / f"{n}.png") for n in FX]),
        ("HAND", [(n, ART / "hand" / f"{n}.png") for n in HAND]),
    ]
    item_files = []
    series_first = []
    series_count = []
    for slot in SLOTS:
        files = sorted(ART.glob(f"items/{slot}_*.png"))
        if len(files) % len(TIERS) != 0 or not files:
            sys.exit(f"items/{slot}_*: need whole series of five tiers")
        series_first.append(len(item_files))
        series_count.append(len(files) // len(TIERS))
        item_files += files
    potion_first = len(item_files)
    item_files += [ART / "items" / "potion_hp.png", ART / "items" / "potion_mp.png"]
    groups.append(("ITEM", [(f.stem, f) for f in item_files]))

    h = ["// Generated by tools/convert_art.py from art/. Do not edit.",
         "#ifndef RENDER_ART_H", "#define RENDER_ART_H", "", "#include <stdint.h>", "",
         "// Texels a column at a time (texels[x * h + y]), index 0 transparent. shades holds",
         "// SHADES + 1 rows of `stride` byte-swapped RGB565 colours: row 0 lit, each next one",
         "// farther into the dark, and the last row the hit flash.",
         "struct Bitmap", "{", "    uint8_t w;", "    uint8_t h;", "    uint8_t stride;",
         "    const uint8_t *texels;", "    const uint16_t *shades;", "};", "",
         f"static const uint8_t SHADES = {SHADES};", ""]
    cpp = ["// Generated by tools/convert_art.py from art/. Do not edit.", '#include "Art.h"', ""]

    for prefix, entries in groups:
        h.append(f"enum {prefix.capitalize()}Art : uint8_t")
        h.append("{")
        for name, _ in entries:
            h.append(f"    ART_{prefix}_{name.upper()},")
        h.append(f"    {prefix}_ART_COUNT")
        h.append("};")
        h.append(f"extern const Bitmap {prefix}_ART[{prefix}_ART_COUNT];")
        h.append("")
        table = []
        for name, path in entries:
            n, w, hh, stride, texels, shades = bitmap(name, path)
            ident = f"{prefix.lower()}_{n}"
            cpp.append(f"static const uint8_t {ident}_texels[] = {{")
            cpp.append(words(texels, 32, "{}"))
            cpp.append("};")
            cpp.append(f"static const uint16_t {ident}_shades[] = {{")
            cpp.append(words(shades))
            cpp.append("};")
            table.append(f"    {{{w}, {hh}, {stride}, {ident}_texels, {ident}_shades}},")
        cpp.append(f"const Bitmap {prefix}_ART[{prefix}_ART_COUNT] = {{")
        cpp += table
        cpp.append("};")
        cpp.append("")

    h.append("// The menus' 16x16 icons, in ItemArt order")
    h.append("extern const uint16_t *const ITEM_ICONS[ITEM_ART_COUNT];")
    h.append(f"static const uint8_t ITEM_SERIES_FIRST[] = {{{', '.join(map(str, series_first))}}};")
    h.append(f"static const uint8_t ITEM_SERIES_COUNT[] = {{{', '.join(map(str, series_count))}}};")
    h.append(f"static const uint8_t ITEM_TIERS = {len(TIERS)};")
    h.append(f"static const uint8_t ITEM_POTION_FIRST = {potion_first};")
    h.append("")
    h.append("#endif // RENDER_ART_H")
    names = []
    for f in item_files:
        ident = f"icon_{f.stem}"
        cpp.append(f"static const uint16_t {ident}[] = {{")
        cpp.append(words(icon565(f)))
        cpp.append("};")
        names.append(ident)
    cpp.append("const uint16_t *const ITEM_ICONS[ITEM_ART_COUNT] = {")
    cpp += [f"    {n}," for n in names]
    cpp.append("};")

    OUT_H.write_text("\n".join(h) + "\n")
    OUT_CPP.write_text("\n".join(cpp) + "\n")
    print(f"{OUT_H.name}, {OUT_CPP.name}: {sum(len(e) for _, e in groups)} bitmaps, {len(item_files)} icons")


if __name__ == "__main__":
    main()
