#!/usr/bin/env python3
"""Converts the artist's PNGs in src/assets/png/sprites/ into src/assets/Sprites.{h,cpp}.

Enemies (enemies/*.png, 64x64) become a SpriteDef: the opaque bounding box, a per-sprite
palette, and the rows run-length encoded as (length, palette index) byte pairs, index 0
being transparent. Pixel art is mostly long runs, so this costs about a sixth of raw
RGB565 and keeps every colour the artist used. EnemySprite draws it at 2x.

Backgrounds (backgrounds/*.png, 64x64 and fully opaque) use the same format and are drawn
behind the enemy of the zone that names them.

Items (items/*.png) are cropped to their opaque area and box-filtered down to the 16x16
RGB565 icons the rest of the UI uses, black transparent like every other icon.

Colours are byte-swapped, as everywhere else in the assets, because pushImage and
pushPixels send words raw.

Run from the repo root: python3 tools/convert_sprites.py
"""
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "assets" / "png" / "sprites"
OUT_H = ROOT / "src" / "assets" / "Sprites.h"
OUT_CPP = ROOT / "src" / "assets" / "Sprites.cpp"

FRAME = 64
ICON = 16
ALPHA_CUTOFF = 128
NEAR_BLACK = 0x0020  # Opaque black in an icon, since 0x0000 is the transparent key


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def swap(c):
    return ((c >> 8) | (c << 8)) & 0xFFFF


def load(path):
    im = Image.open(path).convert("RGBA")
    return im


def convert_sprite(name, path):
    im = load(path)
    if im.size != (FRAME, FRAME):
        sys.exit(f"{path}: expected {FRAME}x{FRAME}, got {im.size}")
    # Drop the soft edge before measuring, so the box only covers what is drawn
    alpha = im.getchannel("A").point(lambda a: 255 if a >= ALPHA_CUTOFF else 0)
    x0, y0, x1, y1 = alpha.getbbox()
    w, h = x1 - x0, y1 - y0

    palette = []
    lookup = {}
    runs = []
    for y in range(y0, y1):
        row = []
        for x in range(x0, x1):
            r, g, b, a = im.getpixel((x, y))
            if a < ALPHA_CUTOFF:
                row.append(0)
                continue
            c = rgb565(r, g, b)
            if c not in lookup:
                palette.append(c)
                lookup[c] = len(palette)
            row.append(lookup[c])
        # Runs never cross a row, so the drawer can decode one row at a time
        i = 0
        while i < w:
            j = i
            while j < w and row[j] == row[i] and j - i < 255:
                j += 1
            runs += [j - i, row[i]]
            i = j
    if len(palette) > 255:
        sys.exit(f"{path}: {len(palette)} colours, the format holds 255")

    cost = len(runs) + 2 * len(palette)
    body = [
        f"static const uint16_t PROGMEM {name}_palette[] = {{{', '.join(f'0x{swap(c):04X}' for c in palette)}}};",
        f"static const uint8_t PROGMEM {name}_runs[] = {{{', '.join(str(v) for v in runs)}}};",
        f"const SpriteDef {name} = {{{x0}, {y0}, {w}, {h}, {name}_palette, {name}_runs}};",
    ]
    return body, cost


def convert_item(name, path):
    im = load(path)
    alpha = im.getchannel("A").point(lambda a: 255 if a >= ALPHA_CUTOFF else 0)
    im = im.crop(alpha.getbbox())
    scale = ICON / max(im.size)
    small = im.resize((max(1, round(im.width * scale)), max(1, round(im.height * scale))), Image.BOX)
    icon = Image.new("RGBA", (ICON, ICON))
    icon.paste(small, ((ICON - small.width) // 2, (ICON - small.height) // 2))

    words = []
    for y in range(ICON):
        for x in range(ICON):
            r, g, b, a = icon.getpixel((x, y))
            if a < ALPHA_CUTOFF:
                words.append(0)
            else:
                words.append(swap(rgb565(r, g, b) or NEAR_BLACK))
    body = [f"const uint16_t PROGMEM {name}[] = {{{', '.join(f'0x{v:04X}' for v in words)}}};"]
    return body, ICON * ICON * 2


def main():
    header = [
        "// Generated by tools/convert_sprites.py from src/assets/png/sprites/. Do not edit.",
        "#ifndef SPRITES_H",
        "#define SPRITES_H",
        "",
        "#include <Arduino.h>",
        "",
        "// An enemy sprite or zone background: the opaque box inside its 64x64 frame, a palette,",
        "// and each row of the box as (length, index) byte pairs. Index 0 is transparent; index i",
        "// is palette[i - 1].",
        "struct SpriteDef",
        "{",
        "    uint8_t x;",
        "    uint8_t y;",
        "    uint8_t w;",
        "    uint8_t h;",
        "    const uint16_t *palette; // Byte-swapped RGB565",
        "    const uint8_t *runs;",
        "};",
        f"static const uint8_t SPRITE_FRAME = {FRAME};",
        "",
    ]
    source = [
        "// Generated by tools/convert_sprites.py from src/assets/png/sprites/. Do not edit.",
        '#include "Sprites.h"',
        "",
    ]

    total = 0
    for kind, convert, decl in (
        ("enemies", convert_sprite, "extern const SpriteDef sprite_{};"),
        ("backgrounds", convert_sprite, "extern const SpriteDef background_{};"),
        ("items", convert_item, "extern const uint16_t image_item_{}_pixels[]; // 16x16"),
    ):
        header.append(f"// {kind.capitalize()}")
        for path in sorted((SRC / kind).glob("*.png")):
            name = {"enemies": "sprite_", "backgrounds": "background_"}.get(kind, "image_item_")
            name = name + path.stem if kind != "items" else f"image_item_{path.stem}_pixels"
            body, cost = convert(name, path)
            total += cost
            header.append(decl.format(path.stem))
            source += body + [""]
            print(f"{kind}/{path.name:20} {cost:6} bytes")
        header.append("")

    header.append("#endif // SPRITES_H")
    OUT_H.write_text("\n".join(header) + "\n")
    OUT_CPP.write_text("\n".join(source))
    print(f"total {total} bytes")


if __name__ == "__main__":
    main()
