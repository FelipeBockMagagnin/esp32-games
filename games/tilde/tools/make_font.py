#!/usr/bin/env python3
"""Bakes tools/fonts/Nunito.ttf (OFL, see OFL.txt beside it) into src/gfx/FontData.cpp: the
printable ASCII glyphs at each size in FONTS, anti-aliased, as 4-bit alpha, two pixels a byte
with each row starting on a byte.

    python3 tools/make_font.py
"""
import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TTF = os.path.join(ROOT, "tools", "fonts", "Nunito.ttf")
OUT = os.path.join(ROOT, "src", "gfx", "FontData.cpp")
WEIGHT = 800
# (name, pixel size): the C++ names of the fonts
FONTS = [("FONT_SMALL", 11), ("FONT_BODY", 13), ("FONT_TITLE", 20)]
FIRST, LAST = 32, 126


def bake(size):
    font = ImageFont.truetype(TTF, size)
    font.set_variation_by_axes([WEIGHT])
    ascent, descent = font.getmetrics()
    glyphs, bitmap = [], bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advance = round(font.getlength(ch))
        box = font.getbbox(ch)
        w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
        offset = len(bitmap)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255)
            px = img.load()
            for y in range(h):
                row = [px[x, y] * 15 // 255 for x in range(w)]
                if len(row) % 2:
                    row.append(0)
                for i in range(0, len(row), 2):
                    bitmap.append(row[i] << 4 | row[i + 1])
        glyphs.append((advance, box[0], box[1], w, h, offset))
    return ascent + descent, ascent, glyphs, bitmap


def main():
    out = ["// Generated by tools/make_font.py from Nunito (SIL Open Font Licence); never edit by hand",
           '#include "Font.h"', ""]
    for name, size in FONTS:
        height, ascent, glyphs, bitmap = bake(size)
        low = name.lower()
        out.append("static const uint8_t %s_BITS[] PROGMEM = {" % low)
        for i in range(0, len(bitmap), 24):
            out.append("    " + ", ".join("0x%02X" % b for b in bitmap[i:i + 24]) + ",")
        out.append("};")
        out.append("static const Glyph %s_GLYPHS[] PROGMEM = {" % low)
        for g in glyphs:
            out.append("    {%d, %d, %d, %d, %d, %d}," % g)
        out.append("};")
        out.append("const Font %s = {%d, %d, %s_GLYPHS, %s_BITS};" % (name, height, ascent, low, low))
        out.append("")
        print(name, size, "px:", len(bitmap), "bytes")
    with open(OUT, "w") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
