#!/usr/bin/env python3
"""Converts the PNGs in src/assets/png/tiles/ into src/assets/Sprites.{h,cpp}, one 16x16
RGB565 icon each, named image_<file stem>_pixels.

A 16x16 PNG is taken as drawn. A larger one (the enemies, drawn at 64x64) is cropped to its
opaque area and box-filtered down to fit.

Colours are byte-swapped because pushImage sends words raw, and pure black is the
transparent key, so an opaque black pixel becomes the nearest colour that is not.

Run from the repo root: python3 tools/convert_sprites.py
"""
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "assets" / "png" / "tiles"
OUT_H = ROOT / "src" / "assets" / "Sprites.h"
OUT_CPP = ROOT / "src" / "assets" / "Sprites.cpp"

ICON = 16
ALPHA_CUTOFF = 128
NEAR_BLACK = 0x0020


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def swap(c):
    return ((c >> 8) | (c << 8)) & 0xFFFF


def to_icon(path):
    im = Image.open(path).convert("RGBA")
    if im.size == (ICON, ICON):
        return im
    alpha = im.getchannel("A").point(lambda a: 255 if a >= ALPHA_CUTOFF else 0)
    im = im.crop(alpha.getbbox())
    scale = ICON / max(im.size)
    small = im.resize((max(1, round(im.width * scale)), max(1, round(im.height * scale))), Image.BOX)
    icon = Image.new("RGBA", (ICON, ICON))
    icon.paste(small, ((ICON - small.width) // 2, (ICON - small.height) // 2))
    return icon


def words(icon):
    out = []
    for y in range(ICON):
        for x in range(ICON):
            r, g, b, a = icon.getpixel((x, y))
            out.append(0 if a < ALPHA_CUTOFF else swap(rgb565(r, g, b) or NEAR_BLACK))
    return out


def main():
    paths = sorted(SRC.glob("*.png"))
    header = ["// Generated by tools/convert_sprites.py; do not edit", "#ifndef SPRITES_H", "#define SPRITES_H", "",
              "#include <Arduino.h>", ""]
    body = ["// Generated by tools/convert_sprites.py; do not edit", '#include "Sprites.h"', ""]
    for path in paths:
        name = f"image_{path.stem}_pixels"
        header.append(f"extern const uint16_t {name}[]; // 16x16")
        values = ", ".join(f"0x{v:04X}" for v in words(to_icon(path)))
        body.append(f"const uint16_t PROGMEM {name}[] = {{{values}}};")
    header += ["", "#endif // SPRITES_H", ""]
    body.append("")
    OUT_H.write_text("\n".join(header))
    OUT_CPP.write_text("\n".join(body))
    print(f"{len(paths)} icons, {len(paths) * ICON * ICON * 2} bytes")


if __name__ == "__main__":
    main()
