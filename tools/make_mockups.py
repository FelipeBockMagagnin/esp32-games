# Prints a floor as "tile,glyph" cells, from the game's own generator
DEEPWELL_DUMP = r"""
#include <cstdio>
#include <cstdlib>
#include "Run.h"
unsigned long millis() { return 0; }
long random(long) { return 0; }
long random(long min, long) { return min; }
int main(int, char **argv)
{
    static Run run;
    Run::Snapshot s = {};
    s.seed = atoi(argv[1]);
    s.floor = atoi(argv[2]);
    s.level = 1;
    s.hp = 1;
    run.load(s);
    int g[MAP_H][MAP_W] = {};
    for (int i = 0; i < Run::MAX_ENTITIES; i++)
    {
        const Entity &e = run.getEntity(i);
        if (e.kind == Entity::ITEM) g[e.y][e.x] = ITEMS[e.type].glyph;
    }
    for (int i = 0; i < Run::MAX_ENTITIES; i++)
    {
        const Entity &e = run.getEntity(i);
        if (e.kind == Entity::ENEMY) g[e.y][e.x] = ENEMIES[e.type].glyph;
    }
    for (int y = 0; y < MAP_H; y++, puts(""))
        for (int x = 0; x < MAP_W; x++)
            printf("%d,%d ", run.getMap().at(x, y), g[y][x]);
}
"""
# TileMap.cpp's sprites, by Tile and by Glyph
DEEPWELL_TILES = ["wall", "floor", "stairs"]
DEEPWELL_GLYPHS = [None, "hero", "small_rat", "slime", "frog", "goblin", "zombie", "frog_wizard", "potion_01a",
                   "coin_03a", "sword_01a", "sword_01c", "sword_01d", "sword_01e", "armor_01a", "armor_01c",
                   "armor_01e"]


def deepwell():
    with tempfile.TemporaryDirectory() as tmp:
        src, exe = Path(tmp) / "dump.cpp", Path(tmp) / "dump"
        src.write_text(DEEPWELL_DUMP)
        game = DEEPWELL / "src" / "rogue"
        subprocess.run(["g++", "-std=c++17", "-I", str(game), "-I", str(DEEPWELL / "tools" / "stub"), str(src),
                        str(game / "Run.cpp"), str(game / "Map.cpp"), "-o", str(exe)], check=True)
        out = subprocess.run([str(exe), str(DEEPWELL_SEED), str(DEEPWELL_FLOOR)], check=True, capture_output=True,
                             text=True).stdout
    grid = [[tuple(map(int, c.split(","))) for c in line.split()] for line in out.splitlines()]

    # The player squares up to an enemy, from the first open cell beside one
    hero = None
    for y, row in enumerate(grid):
        for x, (_, glyph) in enumerate(row):
            if hero is None and DEEPWELL_GLYPHS[glyph] in ("goblin", "zombie"):
                for dx, dy in ((-1, 0), (1, 0), (0, 1), (0, -1)):
                    if grid[y + dy][x + dx] == (1, 0):
                        hero = (x + dx, y + dy)
                        break
    grid[hero[1]][hero[0]] = (1, 1)

    tiles = DEEPWELL / "src" / "assets" / "png" / "tiles"
    icons = {}

    def icon(name):
        # As tools/convert_sprites.py has it: cropped, box-filtered to 16x16, alpha cut at half
        if name not in icons:
            im = Image.open(tiles / f"{name}.png").convert("RGBA")
            if im.size != (16, 16):
                im = im.crop(im.getchannel("A").point(lambda a: 255 if a >= 128 else 0).getbbox())
                scale = 16 / max(im.size)
                small = im.resize((max(1, round(im.width * scale)), max(1, round(im.height * scale))), Image.BOX)
                im = Image.new("RGBA", (16, 16))
                im.paste(small, ((16 - small.width) // 2, (16 - small.height) // 2))
            im.putalpha(im.getchannel("A").point(lambda a: 255 if a >= 128 else 0))
            icons[name] = im
        return icons[name]

    img = Image.new("RGBA", (W, H), T["BG"] + (255,))
    for y, row in enumerate(grid):
        for x, (tile, glyph) in enumerate(row):
            img.paste(icon(DEEPWELL_TILES[tile]), (x * 16, 32 + y * 16))
            if glyph:
                img.alpha_composite(icon(DEEPWELL_GLYPHS[glyph]), (x * 16, 32 + y * 16))
    img = img.convert("RGB")

    d = ImageDraw.Draw(img)
    # A step above the board's rows: this font stands taller than its 8px GLCD
    d.rectangle((4, 2, 87, 12), outline=T["HP_BORDER"], fill=T["HP_TRACK"])
    d.rectangle((5, 3, 5 + 82 * 27 // 38, 11), fill=T["HP_BAR"])
    text(d, (46, 7), "27/38", T["TEXT"], "mm")
    text(d, (236, 1), "F6 Lv4 A10 D3 P2", T["TEXT"], "ra")
    text(d, (4, 12), "You hit the Goblin (8).", T["TEXT"])
    text(d, (4, 21), "The Goblin hits you (3).", T["TEXT_2"])
    return img


SEGMENTS = {"0": "abcdef", "1": "bc", "2": "abged", "3": "abgcd", "4": "fgbc", "5": "afgcd", "6": "afgedc",
            "7": "abc", "8": "abcdefg", "9": "abcdfg"}


def seven_segment(d, cx, cy, s, color, h=48, w=26, t=5, gap=6):
    """TFT_eSPI's font 7: 48px seven-segment digits and a colon"""
    widths = [t if c == ":" else w for c in s]
    x = cx - (sum(widths) + gap * (len(s) - 1)) // 2
    top, mid, bottom = cy - h // 2, cy, cy + h // 2
    for c, cw in zip(s, widths):
        if c == ":":
            d.rectangle((x, mid - 12, x + t - 1, mid - 12 + t - 1), fill=color)
            d.rectangle((x, mid + 8, x + t - 1, mid + 8 + t - 1), fill=color)
        else:
            bars = {
                "a": (x + t, top, x + w - t - 1, top + t - 1), "g": (x + t, mid - t // 2, x + w - t - 1, mid + t // 2),
                "d": (x + t, bottom - t + 1, x + w - t - 1, bottom),
                "f": (x, top + t, x + t - 1, mid - t // 2 - 1), "b": (x + w - t, top + t, x + w - 1, mid - t // 2 - 1),
                "e": (x, mid + t // 2 + 1, x + t - 1, bottom - t), "c": (x + w - t, mid + t // 2 + 1, x + w - 1, bottom - t),
            }
            for seg in SEGMENTS[c]:
                d.rectangle(bars[seg], fill=color)
        x += cw + gap


def pomodoro():
    img = Image.new("RGB", (W, H), T["BG"])
    header(img, "Focus", "Stats", "Stats")
    d = ImageDraw.Draw(img)
    cx, cy, r, thick = 120, 150, 96, 10
    left = 0.68
    box = (cx - r, cy - r, cx + r, cy + r)
    # What is left runs on to 12 o'clock; what has gone is the track after it
    d.arc(box, -90, 270 - 360 * left, fill=T["FRAME_DIM"], width=thick)
    d.arc(box, 270 - 360 * left, 270, fill=T["BAD"], width=thick)
    big_text(img, (cx, cy - 52), "FOCUS", T["BAD"])
    seven_segment(d, cx, cy, "17:04", T["TEXT"])
    for i in range(4):
        dx = cx - 40 + i * 20 + 10
        if i < 2:
            d.ellipse((dx - 5, 265, dx + 5, 275), fill=T["BAD"])
        else:
            d.ellipse((dx - 5, 265, dx + 5, 275), outline=T["FRAME"])
    text(d, (cx, 294), "Confirm start/pause", T["TEXT_DIM"], "ma")
    text(d, (cx, 306), "Up restart - Down skip", T["TEXT_DIM"], "ma")
    return img


