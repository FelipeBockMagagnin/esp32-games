#!/usr/bin/env python3
"""Draws games/<id>/screen.png, a 240x320 picture of each game's screen for the site, from the
games' own sprites and colours instead of a photo of the board.

The pet's tiles are redrawn here after its TileArt.cpp, with the same art colours. Idle Miner's
is no drawing but its Mining screen read back from a board (tools/captures/idle.png, taken with
games/idle/tools/screenshot.py), since a redrawing fell behind the game. Decaf Inferno's floor is filmed by the
game's own renderer (its tools/sim/film.sh, which needs g++) and turned upright, since that game
holds the board on its side. Deepwell's floor is generated by the game's own code, compiled
with g++, and drawn with its tiles; the Pomodoro's Focus screen is redrawn after its layout.
Tilde's Home screen is drawn by the game's own screens on the PC (its tools/shots.sh, which
needs g++ and Pillow). JackHammer's arena is drawn by the game's own renderer (its
tools/frame.sh, which needs g++), under its HUD redrawn after PlayScreen.
Run from the repo root:
python3 tools/make_mockups.py
"""
import random
import subprocess
import tempfile
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
# Screens read back from a board by each game's tools/screenshot.py
CAPTURES = ROOT / "tools" / "captures"
GAMES = ROOT / "games"
DECAF = GAMES / "decaf"
